/*

В качестве функции сложения использовать побайтовый XOR.
Ключевую гамму генерировать в виде последовательности псевдослучайных байт(rand).
Гамма должна быть близка по длине к длине шифр текста.
->
шифрование
Ввод
Пердавать строку для шифрования как параметр командной строки (в челевекочиатемом представлении)
Вывод
[случайный ключ из байт в 16-ричном пердставлении]
[шифрованная строка из байт в 16-ричном представлении]
<-
дешифрование
Ввод
Передавать ключ и строку для дешифрования как параметры командной строки (в 16-ричном представлении)
Вывод
[дешированная строка (в челевекочиатемом представлении)]

*/

void gamma_cipher(char* buff, char* string, char* key, int size_s, int size_k) {
    for (int i = 0; i < size_s; i++) {
        buff[i] = (string[i] ^ key[i % size_k]);
    }
}
